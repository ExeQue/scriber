// Writes docs/agents/mcp-tools.md from the tool list of a running `scriber mcp --headless`.
// Usage: npm run docs:mcp [-- path/to/scriber]   (default: target/debug/scriber, else target/release/scriber)
import { spawn } from 'node:child_process'
import { existsSync, writeFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createInterface } from 'node:readline'

const docs = join(dirname(fileURLToPath(import.meta.url)), '..')
const root = join(docs, '..')
const bin = process.argv[2] ?? ['debug', 'release'].map((p) => join(root, 'target', p, 'scriber')).find(existsSync)
if (!bin || !existsSync(bin)) {
  console.error('No scriber binary found; run `cargo build` first or pass its path.')
  process.exit(1)
}

// A throwaway library file, so listing tools never touches the user's library.
const env = { ...process.env, SCRIBER_LIBRARY: join(mkdtempSync(join(tmpdir(), 'scriber-docs-')), 'library.json') }
const child = spawn(bin, ['mcp', '--headless'], { env, stdio: ['pipe', 'pipe', 'inherit'] })
const pending = new Map()
createInterface({ input: child.stdout }).on('line', (line) => {
  const msg = JSON.parse(line)
  pending.get(msg.id)?.(msg)
})
let next = 1
const call = (method, params = {}) =>
  new Promise((resolve, reject) => {
    const id = next++
    pending.set(id, (m) => (m.error ? reject(new Error(m.error.message)) : resolve(m.result)))
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n')
  })

await call('initialize', { protocolVersion: '2025-03-26', capabilities: {}, clientInfo: { name: 'docs', version: '1' } })
child.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n')
const tools = []
let cursor
do {
  const r = await call('tools/list', cursor ? { cursor } : {})
  tools.push(...r.tools)
  cursor = r.nextCursor
} while (cursor)
child.kill()

// Plain text for Markdown: no HTML tags or Vue interpolation.
const text = (s) => String(s ?? '').replace(/</g, '&lt;').replace(/\{\{/g, '&#123;&#123;')
const cell = (s) => text(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ')
// A short type name for a JSON schema.
function type(s) {
  if (!s) return ''
  if (s.$ref) {
    const name = s.$ref.split('/').pop()
    return `[${name}](#type-${name.toLowerCase()})`
  }
  if (s.const !== undefined) return `\`${s.const}\``
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(' \\| ')
  for (const k of ['anyOf', 'oneOf']) {
    if (s[k]) return s[k].filter((x) => x.type !== 'null').map((x) => type(x)).join(' \\| ')
  }
  if (s.allOf?.length === 1) return type(s.allOf[0])
  const t = [s.type].flat().filter((x) => x && x !== 'null')
  if (t[0] === 'array') return `${type(s.items) || 'any'}[]`
  return t.join(' \\| ') || 'any'
}

tools.sort((a, b) => a.name.localeCompare(b.name))
let md = `# MCP tool reference

<!-- Generated by docs/scripts/gen-mcp-reference.mjs from \`scriber mcp --headless\`; run \`npm run docs:mcp\` after changing tools. Do not edit by hand. -->

Every tool Scriber offers AI agents, as the server lists them (${tools.length} tools). Units are
millimetres, y grows down, angles are degrees clockwise. Most tools also take an optional
\`document\` (a document id from \`list_documents\`); without it they work on the active tab.

${tools.map((t) => `[\`${t.name}\`](#${t.name.replace(/_/g, '-')})`).join(' · ')}
`
// One table row per property of an object schema.
function fields(s, head = 'Field') {
  const props = Object.entries(s.properties ?? {})
  if (!props.length) return ''
  const req = new Set(s.required ?? [])
  let t = `\n| ${head} | Type | Required | Description |\n|---|---|---|---|\n`
  for (const [name, p] of props) t += `| \`${name}\` | ${type(p)} | ${req.has(name) ? 'yes' : ''} | ${cell(p.description)} |\n`
  return t
}
// Shared types ($defs) of all tools, by name; the first schema wins (they come from the same Rust type).
const defs = new Map()
for (const t of tools) {
  for (const [name, d] of Object.entries(t.inputSchema?.$defs ?? {})) if (!defs.has(name)) defs.set(name, d)
}

for (const t of tools) md += `\n## ${t.name}\n\n${text(t.description)}\n${fields(t.inputSchema ?? {}, 'Parameter')}`

md += '\n## Types\n\nThe argument types the tools above refer to.\n'
for (const [name, d] of [...defs].sort(([a], [b]) => a.localeCompare(b))) {
  md += `\n### ${name} {#type-${name.toLowerCase()}}\n\n`
  if (d.description) md += `${text(d.description)}\n\n`
  const variants = d.oneOf ?? d.anyOf
  if (d.properties) md += fields(d)
  else if (variants && variants.some((v) => v.properties)) {
    for (const v of variants) {
      const tag = Object.entries(v.properties ?? {}).find(([, p]) => p.const ?? p.enum?.length === 1)
      const label = tag ? `\`${tag[0]}: ${tag[1].const ?? tag[1].enum[0]}\`` : type(v)
      md += `**${label}**${v.description ? ': ' + cell(v.description) : ''}\n${fields(v)}\n`
    }
  } else md += `One of: ${type(d)}\n` + (variants ? variants.filter((v) => v.description).map((v) => `- ${type(v)}: ${cell(v.description)}\n`).join('') : '')
}
const out = join(docs, 'agents', 'mcp-tools.md')
writeFileSync(out, md)
console.log(`Wrote ${tools.length} tools to ${out}`)
